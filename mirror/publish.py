#!/usr/bin/env python3
"""Builds the public mirror's Lakebed capsule from exosphere/static, and deploys it.

    python3 mirror/publish.py              build the capsule and deploy it
    python3 mirror/publish.py --no-deploy  build only

The capsule is generated, so change the site in exosphere/static and the mirror here, then run
this again. Lakebed hosts one client bundle, not loose files: the page's markup and CSS (fonts
inlined) go into client/site.ts and app.js into client/app.ts. The ingest secret comes from
EXOSPHERE_MIRROR_SECRET_FILE, made on the first run, and goes to Lakebed as server env.
"""

import base64
import json
import os
import re
import secrets
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
STATIC = HERE.parent / "exosphere/static"
CAPSULE = Path(os.environ.get("EXOSPHERE_CAPSULE", "~/lakebed-apps/exosphere")).expanduser()
SECRET = Path(os.environ.get("EXOSPHERE_MIRROR_SECRET_FILE", "~/.config/exosphere/mirror.secret")).expanduser()
NODE_BIN = Path(os.environ.get("LAKEBED_NODE_BIN", "~/.local/share/node22/bin")).expanduser()
GENERATED = "// Generated by mirror/publish.py in the exosphere repo. Edit exosphere/static there, not this file.\n"

html = (STATIC / "index.html").read_text()
body = re.search(r"<body>(.*)</body>", html, re.S).group(1)
body = re.sub(r"\s*<script\b.*?</script>", "", body, flags=re.S).strip()

css = (STATIC / "style.css").read_text()
for font in re.findall(r"url\((fonts/[^)]+\.woff2)\)", css):
    data = base64.b64encode((STATIC / font).read_bytes()).decode()
    css = css.replace(f"url({font})", f"url(data:font/woff2;base64,{data})")

script = (STATIC / "app.js").read_text()
if re.search(r"^\s*(import|export)\b", script, re.M):
    sys.exit("app.js has imports or exports now; publish.py wraps it in a function and can't keep those")

for folder in ("client", "server"):
    (CAPSULE / folder).mkdir(parents=True, exist_ok=True)
(CAPSULE / "client/site.ts").write_text(f"{GENERATED}export const BODY = {json.dumps(body)};\nexport const CSS = {json.dumps(css)};\n")
(CAPSULE / "client/app.ts").write_text(f"{GENERATED}// @ts-nocheck\nexport async function start() {{\n{script}\n}}\n")
shutil.copy(HERE / "client/index.tsx", CAPSULE / "client/index.tsx")
shutil.copy(HERE / "server/index.ts", CAPSULE / "server/index.ts")
shutil.copy(STATIC / "icon.svg", CAPSULE / "favicon.svg")
(CAPSULE / ".gitignore").write_text(".lakebed/\n.env.lakebed.server\n")
(CAPSULE / "README.md").write_text(
    "The public, read-only mirror of an exosphere feed. Generated by `mirror/publish.py` in the exosphere repo;\n"
    "change it there. `exosphere mirror` on the real install pushes the posts to `/api/mirror`.\n"
)

if not SECRET.exists():
    SECRET.parent.mkdir(parents=True, exist_ok=True)
    SECRET.write_text(secrets.token_urlsafe(32) + "\n")
    SECRET.chmod(0o600)
env = CAPSULE / ".env.lakebed.server"
env.write_text(f"MIRROR_SECRET={SECRET.read_text().strip()}\n")
env.chmod(0o600)

print(f"capsule built in {CAPSULE}")
if "--no-deploy" not in sys.argv:
    path = {**os.environ, "PATH": f"{NODE_BIN}:{os.environ['PATH']}"}
    subprocess.run(["npx", "lakebed", "deploy"], cwd=CAPSULE, env=path, check=True)
